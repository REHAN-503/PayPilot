'use client';

import * as React from 'react';
import Link from 'next/link';
import { useQuery } from '@tanstack/react-query';
import { ShoppingBag, ArrowRight, Clock, Layers } from 'lucide-react';
import { DashboardShell } from '../../components/layout/DashboardShell';
import { Card, CardContent } from '../../components/ui/card';
import { Badge } from '../../components/ui/badge';
import { Button } from '../../components/ui/button';
import { Skeleton } from '../../components/ui/progress';
import { api } from '../../lib/api';
import { formatCurrency, formatDate } from '../../lib/utils';

export default function PlansListPage() {
  const { data: plans, isLoading } = useQuery({
    queryKey: ['plans'],
    queryFn: () => api.getPlans(),
  });

  return (
    <DashboardShell>
      <div className="space-y-6">
        <div className="flex items-center justify-between">
          <div>
            <h1 className="text-2xl font-bold text-[var(--ink)] tracking-tight flex items-center gap-2.5">
              <ShoppingBag className="w-6 h-6 text-[var(--ledger)]" />
              Purchase Plans
            </h1>
            <p className="text-xs sm:text-sm text-[var(--ink-3)] mt-1">
              Deterministic procurement packages generated by PayPilot autonomous agents.
            </p>
          </div>

          <Link href="/">
            <Button variant="glow" size="sm">
              New Plan
            </Button>
          </Link>
        </div>

        {isLoading ? (
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <Skeleton className="h-44 w-full" />
            <Skeleton className="h-44 w-full" />
          </div>
        ) : plans && plans.length > 0 ? (
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {plans.map((plan) => {
              const item = plan.items?.[0];
              const isApproved = plan.status === 'APPROVED';
              const isPending = plan.status === 'AWAITING_APPROVAL';

              return (
                <Card
                  key={plan.id}
                  className="border-[var(--rule)] bg-[var(--card)]/70 hover:border-[var(--rule)] transition-all group flex flex-col justify-between"
                >
                  <CardContent className="p-5 space-y-4">
                    <div className="flex items-center justify-between">
                      <div className="flex items-center gap-2">
                        <Badge
                          variant={
                            isApproved ? 'success' : isPending ? 'warning' : 'secondary'
                          }
                        >
                          {plan.status.replace('_', ' ')}
                        </Badge>
                        <span className="text-xs font-mono text-[var(--ink-3)]">
                          v{plan.version}
                        </span>
                      </div>
                      <div className="text-right">
                        <span className="text-xl font-bold text-[var(--ink)]">
                          {formatCurrency(plan.total)}
                        </span>
                        <span className="text-xs text-[var(--ink-3)] ml-1">USD</span>
                      </div>
                    </div>

                    <div>
                      <h3 className="font-semibold text-[var(--ink)] group-hover:text-[var(--ledger)] transition-colors line-clamp-1">
                        {item?.productName || 'Procurement Order'}
                      </h3>
                      <p className="text-xs text-[var(--ink-3)] mt-1 line-clamp-2 leading-relaxed">
                        {plan.explanation || 'Autonomous plan generated based on prompt requirements.'}
                      </p>
                    </div>

                    <div className="flex items-center justify-between pt-3 border-t border-[var(--rule)] text-xs text-[var(--ink-3)]">
                      <div className="flex items-center gap-1.5">
                        <Clock className="w-3.5 h-3.5 text-[var(--ink-3)]" />
                        <span>{formatDate(plan.createdAt)}</span>
                      </div>

                      <Link href={`/plans/${plan.id}`}>
                        <Button variant="ghost" size="sm" className="h-8 text-xs text-[var(--ledger)] group-hover:text-[var(--ink)]">
                          Inspect Plan
                          <ArrowRight className="w-3.5 h-3.5 ml-1" />
                        </Button>
                      </Link>
                    </div>
                  </CardContent>
                </Card>
              );
            })}
          </div>
        ) : (
          <div className="text-center p-12 rounded-3xl border border-dashed border-[var(--rule)] bg-[var(--card)]/30">
            <Layers className="w-10 h-10 text-[var(--ink-3)] mx-auto mb-3" />
            <h3 className="text-sm font-semibold text-[var(--ink-2)]">No purchase plans found</h3>
            <p className="text-xs text-[var(--ink-3)] mt-1 max-w-sm mx-auto">
              Ask PayPilot in the Command Center to plan an order.
            </p>
            <Link href="/" className="inline-block mt-4">
              <Button variant="glow" size="sm">
                Create First Plan
              </Button>
            </Link>
          </div>
        )}
      </div>
    </DashboardShell>
  );
}

